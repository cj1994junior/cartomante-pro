const CACHE = "cartomante-pro-v5";
const SHELL = [
  "/",
  "/app",
  "/dev",
  "/manifest.webmanifest",
  "/icon.svg",
  "/images/tarot-hero.jpg",
  "/images/tarot-cards.jpg",
  "/images/tarot-crystal.jpg",
  "/images/spiritual-works.jpg",
  "/images/holistic-therapy.jpg",
];

self.addEventListener("install", (event) => {
  event.waitUntil(
    caches
      .open(CACHE)
      .then((cache) => cache.addAll(SHELL).catch(() => undefined))
      .then(() => self.skipWaiting()),
  );
});

self.addEventListener("activate", (event) => {
  event.waitUntil(
    caches
      .keys()
      .then((keys) => Promise.all(keys.filter((key) => key !== CACHE).map((key) => caches.delete(key))))
      .then(() => self.clients.claim()),
  );
});

self.addEventListener("fetch", (event) => {
  const request = event.request;
  if (request.method !== "GET") return;
  const url = new URL(request.url);
  if (url.origin !== self.location.origin) return;

  if (url.pathname.startsWith("/api/")) {
    event.respondWith(fetch(request).catch(() => Response.json({ error: "offline" }, { status: 503 })));
    return;
  }

  // Respostas RSC do Next.js são dinâmicas: nunca servir uma navegação de uma versão antiga.
  if (request.headers.has("rsc") || request.headers.has("next-router-state-tree") || url.searchParams.has("_rsc")) {
    event.respondWith(fetch(request));
    return;
  }

  if (request.mode === "navigate") {
    event.respondWith(
      fetch(request)
        .then((response) => {
          const copy = response.clone();
          caches.open(CACHE).then((cache) => cache.put(request, copy));
          return response;
        })
        .catch(() => caches.match(request).then((cached) => cached || caches.match("/app"))),
    );
    return;
  }

  event.respondWith(
    caches.match(request).then(
      (cached) =>
        cached ||
        fetch(request).then((response) => {
          if (response.ok && response.type === "basic") {
            const copy = response.clone();
            caches.open(CACHE).then((cache) => cache.put(request, copy));
          }
          return response;
        }),
    ),
  );
});
